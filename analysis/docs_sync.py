"""Regenerate the numeric passages of the design documents from the result files, so they cannot go stale (AERO-30, MFG-01).

A generated block sits between  <!-- gen:NAME -->  and  <!-- /gen:NAME -->  in a Markdown file; everything between the markers
is replaced on every run. Text outside the markers is hand-written and must not quote a sized number.

Run after the sizing / aero / structures chain:  py analysis/docs_sync.py   (prints which blocks changed; exit 1 if a marker is missing)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
J = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))


def kv(path):
    out = {}
    p = ROOT / path
    if p.exists():
        for l in p.read_text(encoding="utf-8").splitlines():
            if "=" in l and not l.startswith("#"):
                k, v = l.split("=", 1); out[k] = v.split("|")[0]
    return out


def blocks():
    R = J("analysis/results.json"); C = R["concepts"]["C0"]; S, G, P, ST, CG, B = C["sized"], C["geo"], C["params"], C["struct"], C["cg"], C["bom"]
    A = J("analysis/aero/aero_results.json"); L = J("analysis/structures/landing.json") if (ROOT / "analysis/structures/landing.json").exists() else None
    M = J("analysis/mass/mass_budget.json") if (ROOT / "analysis/mass/mass_budget.json").exists() else None
    sim = kv("cad/sim/results.txt")
    pk = C["pick"]
    rf_min = 240e6 / ST["sigJ"]
    out = {}
    land = ""
    if L:
        lo = min(c["cases"]["normal"]["RF_yield_min"] for c in L["corners"].values()); hi = min(c["cases"]["hard"]["RF_yield_min"] for c in L["corners"].values())
        land = (f"- Landing (analysis/structures/landing.py): touchdown at Q_LAND_FINAL_SPD {L['inputs']['land_speed']['value_mps']} m/s "
                f"(firmware/vtol_c0.param) gives reserve factor ≥ {lo:.2f} on the 6061-T6 minimum yield at every gear corner, and ≥ {hi:.2f} "
                f"at twice that speed (hard touchdown); the booms are treated as cantilevers from rigid wing clamps, which over-predicts the load.")
    out["outcomes"] = "\n".join([
        f"- Generated by analysis/docs_sync.py from analysis/results.json ({R['generated']}), analysis/aero/aero_results.json ({A['generated']})"
        + (f" and analysis/mass/mass_budget.json" if M else "") + ". Do not edit inside this block.",
        f"- Mass: MTOW {S['m']:.2f} kg (R2: below the 8–15 kg working target, under the 25 kg cap). Every item the sizing does not derive "
        f"from geometry is calibrated to the CAD roll-up with the print settings (analysis/mass/mass_budget.py"
        + (f": bottom-up {M['total_kg']:.2f} kg" if M else "") + ").",
        f"- Wing: S {S['S']:.3f} m², chord {S['chord']*1000:.1f} mm, AR {S['AR']:.2f}, span {P['span']} m, sized on CL_max {P['CLmax']:.3f} "
        f"at the {P['Vs']} m/s design stall (R11 ≤ 12 m/s); the aero package gives stall {A['stall']['V_stall_mps']:.2f} m/s at its CL_max "
        f"{A['stall']['CL_max_3D']:.3f} ({A['stall']['margin_to_R11_pct']:.1f} % speed margin to R11).",
        f"- Propulsion (R13): 4 × {C['motor'] if isinstance(C['motor'], str) else 'X4110S'} lift units; hover T/W {S['TW']:.2f} on the maker's 22.2 V table, "
        f"hover {S['P_hover']:.0f} W / {S['I_hover']:.1f} A, transition peak {S['I_trans']:.0f} A (EST, 20 s); pack {pk['id']}.",
        f"- Endurance (R10): {S['t_cruise_avail_min']:.1f} min cruise available after {P['tHover']} s hover + {P['tTrans']} s transition with the "
        f"{P['reserve']*100:.0f} % reserve (design margin 11.5 min).",
        f"- CG and stability: battery at x = {CG['xb']:.3f} m (fits: furthest forward station {CG['xbMax']:.3f} m) puts the CG at "
        f"{CG['pct']['target']:.0f} % MAC with no ballast; neutral point {CG['pct']['np']:.1f} % MAC; static margin {G['SM']*100:.1f} %.",
        f"- Structure: joiner {ST['sigJ']/1e6:.0f} MPa at {ST['nUlt']} g ultimate (Schrenk root moment {ST['Mroot']:.1f} N·m): reserve factor "
        f"{ST['MS_J']:.2f} on the 275 MPa library yield, {rf_min:.2f} on the 240 MPa minimum. Boom first mode {ST['fn']:.1f} Hz with the "
        f"{ST['mTip']*1000:.0f} g lift unit." + (f" FEA (cad/sim/results.txt): boom {sim.get('boom_vm_max_fine', '—')} MPa, spar {sim.get('spar_vm_max_fine', '—')} MPa." if sim else ""),
        land,
        f"- Budget (R6/R7): committed ${B['total']:.2f} incl. 10.25 % tax and ${B['shipping']:.0f} shipping; crash reserve ${B['crash']:.2f}"
        + (" (below the R7 $100 target: see Assumptions)." if B['crash'] < 100 else " (R7 met)."),
    ])
    # hardware-spec J05 (boom clamp loads) and J10 (wing bolt) from cad/params.txt
    pt = kv("cad/params.txt"); comps = [l[5:].split("|") for l in (ROOT / "cad/params.txt").read_text(encoding="utf-8").splitlines() if l.startswith("comp=")]
    cx = lambda name: next(float(c[1]) for c in comps if c[0] == name)
    xf, xcf, xcr, T = float(pt["xFront"]), cx("Boom_Clamp_F_Upper"), cx("Boom_Clamp_R_Upper"), ST["Tmax"]
    arm, spc = xf - xcf, xcf - xcr
    rr = T * arm / spc; rf = T + rr
    out["j05_load"] = (f"- **Load check (calc, generated by analysis/docs_sync.py from cad/params.txt):** one lift motor at T_max {T:.2f} N "
                       f"(analysis/results.json struct.Tmax). Front motor x {xf:.4f}, clamps at x {xcf:.4f} and {xcr:.4f}, so the arm from the "
                       f"front clamp is {arm:.4f} m and the clamp spacing {spc:.4f} m. Worst case is a single motor (differential thrust): rear clamp "
                       f"tension = {T:.2f} × {arm:.4f} / {spc:.4f} = {rr:.1f} N ({rr/2:.1f} N per screw); front clamp compression {rf:.1f} N. "
                       f"Insert pull-out capacity in PETG is not in the repo (—): first-article coupon test M3.")
    sd = float(pt["pillarH"]) * 1000; sf = float(pt["pillarSpot"]) * 1000; nd = float(pt["pillarNutDepth"]) * 1000; L = float(pt["wingBoltL"]) * 1000
    past = (nd - 5.0) - (sd - sf - L)   # screw end below the nut's outer face: nut outer face at nd - 5.0 (nylock 5.0 thick), screw end at sd - sf - L
    out["j10_geom"] = (f"- **Fastener (generated from cad/params.txt):** F09, ISO 7380 M5 × {L:.0f} A2 + N02 M5 nylock, 1 per side, vertical, at 70 % chord, "
                       f"z ±{float(pt['boltZ'])*1000:.0f} mm (params boltZ).\n"
                       f"- **Geometry:** PETG panel root tongue (6.4 mm thick, 20 mm wide) projects 25 mm inboard into a slot in a PETG bolt pillar "
                       f"(Ø16, full section height {sd:.1f} mm) in the saddle. Hole Ø5.5. Head in a Ø10.3 × {sf:.1f} spot-face. Nut pocket 8.2 AF × "
                       f"{nd:.1f} deep from the lower surface. Screw end {past:.1f} mm past the nut's outer face nominal; the tolerance stack is ±1.9 mm "
                       f"worst case, so at least {past-1.9:.1f} mm (two 0.8 mm threads) always pass the nylon ring (cad/params.mjs rule, MFG-09).")
    out["stall_status"] = (f"Current adopted design (generated by analysis/docs_sync.py from analysis/results.json {R['generated']}): chord "
                           f"{S['chord']*1000:.1f} mm, S {S['S']:.3f} m², MTOW {S['m']:.3f} kg, cruise {S['t_cruise_avail_min']:.2f} min; "
                           f"the tables below are the 2026-10-25 trade as run then.")
    return out


def main():
    gen = blocks(); changed, missing = [], []
    for path, names in (("docs/DESIGN-BASIS.md", ["outcomes"]), ("docs/research/stall-margin.md", ["stall_status"]),
                        ("docs/research/hardware-spec.md", ["j05_load", "j10_geom"])):
        p = ROOT / path; s = p.read_text(encoding="utf-8")
        for n in names:
            m = re.search(rf"(<!-- gen:{n} -->\n)(.*?)(<!-- /gen:{n} -->)", s, re.S)
            if not m:
                missing.append(f"{path}:{n}"); continue
            body = gen[n].rstrip("\n") + "\n"
            if m.group(2) != body:
                s = s[:m.start(2)] + body + s[m.end(2):]; changed.append(f"{path}:{n}")
        p.write_text(s, encoding="utf-8", newline="\n")
    print("changed:", changed or "none"); print("missing markers:", missing or "none")
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
